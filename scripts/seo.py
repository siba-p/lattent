"""Search and sharing metadata for every page, kept in one managed block before </head>:
the web-app manifest link, canonical URL, Open Graph and Twitter tags (only those a page does not set itself),
structured data (Organization, WebSite and SoftwareApplication on the home page;
WebApplication and breadcrumbs on tool pages; breadcrumbs on solution pages), and noindex
for pages that should not appear in search. Idempotent; run after the page generators
(they call it) or after editing any page by hand:

    python3 scripts/seo.py

The site address comes from `site:` in assets/js/config.js, so scripts/set-domain.py and
this script stay in step.
"""
import html
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cfg = open(os.path.join(ROOT, "assets", "js", "config.js"), encoding="utf-8").read()
BASE = "https://" + re.search(r"site: '([^']+)'", cfg).group(1).strip("/") + "/"
SUPPORT = (re.search(r"support: '([^']*)'", cfg) or [None, ""])[1]
FOUNDERS = re.findall(r"\{ name: '([^']+)', url: '([^']*)' \}", (re.search(r"founders: \[(.*?)\]", cfg, re.S) or [None, ""])[1])
IMAGE = BASE + "assets/img/og.png"
SKIP_DIRS = {".git", "node_modules", "assets", "tests", "docs", "supabase", "scripts"}
NOINDEX = {"404.html", "account/index.html"}
CALCULATORS = {"dose-response/index.html", "enzyme-kinetics/index.html", "qpcr/index.html", "standard-curve/index.html"}
START, END = "<!-- seo: generated by scripts/seo.py -->", "<!-- /seo -->"
block_re = re.compile(r"\n?" + re.escape(START) + r".*?" + re.escape(END), re.S)


def text(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s or "")).strip()


def ld(obj):
    return '<script type="application/ld+json">' + json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/") + "</script>"


def crumbs(*items):
    return {"@context": "https://schema.org", "@type": "BreadcrumbList",
            "itemListElement": [{"@type": "ListItem", "position": i + 1, "name": n, "item": u} for i, (n, u) in enumerate(items)]}


def app(name, url, desc, kind="WebApplication"):
    return {"@context": "https://schema.org", "@type": kind, "name": name, "url": url, "description": desc,
            "applicationCategory": "EducationalApplication", "applicationSubCategory": "Scientific data analysis",
            "operatingSystem": "Any (runs in a web browser)", "isAccessibleForFree": True,
            "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
            "publisher": {"@type": "Organization", "name": "Lattent", "url": BASE}}


changed = 0
for d, dirs, files in os.walk(ROOT):
    dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
    for f in sorted(files):
        if not f.endswith(".html"):
            continue
        p = os.path.join(d, f)
        rel = os.path.relpath(p, ROOT).replace(os.sep, "/")
        src = open(p, encoding="utf-8").read()
        page = block_re.sub("", src)
        if "</head>" not in page:
            continue
        head = page.split("</head>", 1)[0]
        url = BASE + (rel[:-len("index.html")] if rel.endswith("index.html") else rel)
        title = text((re.search(r"<title>(.*?)</title>", head, re.S) or [None, "Lattent"])[1])
        desc = html.unescape((re.search(r'<meta name="description" content="([^"]*)"', head) or [None, ""])[1])
        h1 = text((re.search(r"<h1[^>]*>(.*?)</h1>", page, re.S) or [None, title])[1])
        has = lambda attr: re.search(r'<meta (?:property|name)="' + re.escape(attr) + '"', head)
        # 404.html is served at any depth, so it needs a path from the site root
        prefix = re.sub(r"^https://[^/]+", "", BASE) if rel == "404.html" else "../" * rel.count("/")
        out = ['<link rel="manifest" href="' + prefix + 'manifest.webmanifest">'] if 'rel="manifest"' not in head else []
        if rel in NOINDEX:
            out.append('<meta name="robots" content="noindex">')
        else:
            if 'rel="canonical"' not in head:
                out.append(f'<link rel="canonical" href="{html.escape(url)}">')
            tags = [("og:type", "website"), ("og:site_name", "Lattent"), ("og:url", url), ("og:title", title), ("og:description", desc), ("og:image", IMAGE)]
            out += [f'<meta property="{k}" content="{html.escape(v)}">' for k, v in tags if v and not has(k)]
            if not has("twitter:card"):
                out.append('<meta name="twitter:card" content="summary_large_image">')
            if rel == "index.html":
                org = {"@context": "https://schema.org", "@type": "Organization", "name": "Lattent", "url": BASE,
                       "logo": BASE + "assets/img/apple-touch-icon.png", "sameAs": ["https://github.com/siba-p/lattent"],
                       "founder": [dict({"@type": "Person", "name": n}, **({"url": u} if u else {})) for n, u in FOUNDERS]}
                if SUPPORT:
                    org["email"] = SUPPORT
                out.append(ld(org))
                out.append(ld({"@context": "https://schema.org", "@type": "WebSite", "name": "Lattent", "url": BASE}))
                out.append(ld(app("Lattent Studio", BASE + "studio/", desc, "SoftwareApplication")))
            elif rel.startswith("tools/") and rel != "tools/index.html":
                out.append(ld(app(h1, url, desc)))
                out.append(ld(crumbs(("Lattent", BASE), ("Quick tools", BASE + "tools/"), (h1, url))))
            elif rel.startswith("solutions/") and rel != "solutions/index.html":
                out.append(ld(crumbs(("Lattent", BASE), ("Solutions", BASE + "solutions/"), (title.replace(" | Lattent", ""), url))))
            elif rel in CALCULATORS:
                out.append(ld(app(title.replace(" | Lattent", ""), url, desc)))
        new = page.replace("</head>", START + "\n" + "\n".join(out) + "\n" + END + "\n</head>", 1) if out else page
        if new != src:
            open(p, "w", encoding="utf-8").write(new)
            changed += 1
print(f"seo: {changed} pages updated for {BASE}")
